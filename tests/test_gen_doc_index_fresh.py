"""索引新鲜度的钉子（卡 F9 · T-AG525）。

## 为什么要有这份（判据 3）

`tests/test_gen_doc_index.py` 一直把「真仓库一致」这件事交给验收命令
`python -X utf8 scripts/gen_doc_index.py --check` —— 也就是「人记得的时候才跑」。
实测 2026-10-29 它是红的（`docs/INDEX.md` 自报 297 篇、盘上 305 篇），而没有任何门
在跑它。这份钉子的活儿就是把那条验收命令搬进 pytest 门：

1. **真仓**：子进程跑 `--check`，必须退 0（`pytest` 门每趟全量都会跑到这里）；
2. **保行尾**：写盘跟着目标文件原来的行尾走 —— CRLF 目标重算后 `\\r\\n` 数不变、
   裸 `\\n` 为 0；LF 目标也不会被强行改成 CRLF（证明它读的是盘上现状，不是写死常量）；
3. **反向**：手改产物一行 ⇒ 必须退 1 且**点名行号**，只报「有差异」不算咬住。

判据 1 用的是**子进程**而不是 `gi.main([...])`：同进程会把 `sys.modules` 带进来，
一旦哪天有人在进程内改了 `ROOT`，这条钉子就会静默变成「测自己」。
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPT = ROOT / "scripts" / "gen_doc_index.py"
_MARK = "<!-- generated by scripts/gen_doc_index.py; do not edit -->"


def _run(args: list[str]) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, "-X", "utf8", str(SCRIPT), *args],
        cwd=str(ROOT),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )


def _write(root: Path, rel: str, text: str, newline: str = "\n") -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline=newline)
    return path


def _fm(**fields: str) -> str:
    body = "".join(f"{key}: {value}\n" for key, value in fields.items())
    return f"---\n{body}---\n"


# ------------------------------------------------------- 判据 1：真仓必须一致


def test_the_real_index_matches_the_real_tree() -> None:
    """真仓 `--check` 必须退 0 —— 这是本卡要补上的那个「没人跑」的判据。"""
    done = _run(["--check"])
    assert done.returncode == 0, (
        "真仓的 docs/INDEX.md 与文件不一致（判据 1 红）。"
        "修法：python -X utf8 scripts/gen_doc_index.py\n"
        f"--- stdout ---\n{done.stdout}\n--- stderr ---\n{done.stderr}"
    )
    assert "[OK  ] docs/INDEX.md" in done.stdout


# --------------------------------------------------------- 判据 2：行尾跟着走


def test_crlf_target_stays_crlf(tmp_path: Path) -> None:
    """CRLF 的产物重算后仍然是纯 CRLF（不整文件翻转）。"""
    _write(tmp_path, "docs/a.md", _fm(title="甲", mode="tutorial") + "\n正文\n")
    # ★ 文本里只写 `\n`，行尾交给 newline= 去翻 —— 两处都写 `\r\n` 会变成 `\r\r\n`
    placeholder = _MARK + "\n占位\n"
    index = _write(tmp_path, "docs/INDEX.md", placeholder, newline="\r\n")
    before = index.read_bytes().count(b"\r\n")

    done = _run(["--root", str(tmp_path), "--target", "docs"])
    assert done.returncode == 0, done.stdout + done.stderr

    raw = index.read_bytes()
    crlf = raw.count(b"\r\n")
    lf = raw.count(b"\n")
    assert crlf > before, "产物没写进去（行尾判据会变成空转）"
    assert lf == crlf, (
        "重算后出现裸 LF：生成器把行尾翻成 LF 了（判据 2 红）"
        f"（crlf={crlf} lf={lf}）"
    )


def test_lf_target_stays_lf(tmp_path: Path) -> None:
    """LF 的产物也不会被强行改成 CRLF —— 判据读的是盘上现状，不是写死常量。"""
    _write(tmp_path, "docs/a.md", _fm(title="甲", mode="tutorial") + "\n正文\n")
    index = _write(tmp_path, "docs/INDEX.md", _MARK + "\n占位\n", newline="\n")

    done = _run(["--root", str(tmp_path), "--target", "docs"])
    assert done.returncode == 0, done.stdout + done.stderr

    raw = index.read_bytes()
    assert raw.count(b"\r\n") == 0, "LF 目标被改成了 CRLF（判据 2 的对称半边红）"
    assert raw.count(b"\n") > 2


def test_a_missing_target_defaults_to_crlf(tmp_path: Path) -> None:
    """目标不存在时用 CRLF（本仓工作区常态），不是 `\\n`。"""
    _write(tmp_path, "docs/a.md", _fm(title="甲", mode="tutorial") + "\n正文\n")

    done = _run(["--root", str(tmp_path), "--target", "docs"])
    assert done.returncode == 0, done.stdout + done.stderr

    raw = (tmp_path / "docs/INDEX.md").read_bytes()
    assert raw.count(b"\r\n") > 2 and raw.count(b"\n") == raw.count(b"\r\n")


# --------------------------------------------------- 判据 3 的反向：手改要咬


def test_hand_edit_is_red_and_names_the_line(tmp_path: Path) -> None:
    """手改一行 ⇒ 退 1，且**点名行号**（只报「有差异」不算咬住）。"""
    _write(tmp_path, "docs/a.md", _fm(title="甲", mode="tutorial") + "\n正文\n")
    assert _run(["--root", str(tmp_path), "--target", "docs"]).returncode == 0

    index = tmp_path / "docs/INDEX.md"
    text = index.read_text(encoding="utf-8")
    index.write_text(text.replace("甲", "甲（手改）", 1), encoding="utf-8", newline="\r\n")

    done = _run(["--root", str(tmp_path), "--target", "docs", "--check"])
    assert done.returncode == 1, "手改之后 `--check` 居然退 0（判据 3 红）"
    assert "第 " in done.stdout and "行" in done.stdout, (
        "报错没点名行号，只说了「有差异」：\n" + done.stdout
    )
