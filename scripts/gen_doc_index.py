"""文档索引机器化（卡 F2 · T-AG450）—— 索引由文件头 frontmatter 生成，不手写。

## 为什么

`复盘/INDEX.md` 自称「587 篇、约 284 万字」，一篇都没法核对；`docs/` 干脆没有索引，
新窗口只能靠 `AGENTS.md` 的路由 + `ls` 瞎猜。手写索引的失败模式不是「写错」，而是
**必然过期** —— 它记录的量全都是文件系统的事实。所以这里只做一件事：
**把索引变成文件系统的投影**，一个字节都不抄正文。

## 判据怎么落地（对应卡 §判据 1–5）

1. `--check`：一致退 0；不一致退 1，并**逐行点名**哪几行不一样（不是只说「有差异」）。
2. 内容只读 frontmatter 的 `title / mode / status / owner / supersedes`；没有 frontmatter
   的文件进「未标注」段，**如实计数，不猜不补**（不拿 `# 标题` 顶替 `title`）。
3. 生成物首行是 `<!-- generated by scripts/gen_doc_index.py; do not edit -->`；
   删掉它、或手改任何一行，`--check` 都红。
4. `复盘/INDEX.md` 的 L0 段表与「历史与被推翻」也由脚本算（frontmatter + 路径前缀），
   不复用手写数字；**判不出来就报 skip**（没有 frontmatter ⇒ 无从知道它是否被推翻）。
5. 索引是**第二层**：`AGENTS.md` 仍只做路由 —— 「薄入口 → 索引 → 具体页」。

## 用法

    python -X utf8 scripts/gen_doc_index.py                        # 写盘（只写已接管的目标）
    python -X utf8 scripts/gen_doc_index.py --check                # 只核对（门禁 / 验收用）
    python -X utf8 scripts/gen_doc_index.py --stats                # 只打印各段计数
    python -X utf8 scripts/gen_doc_index.py --target docs --check  # 只查一个目标
    python -X utf8 scripts/gen_doc_index.py --adopt 复盘/INDEX.md  # 接管盘上的手写版

★ 为什么不默认接管 `复盘/INDEX.md`：卡 F2 的白名单只有 `scripts/gen_doc_index.py` /
`tests/test_gen_doc_index.py` / `docs/INDEX.md` 三件，而 `复盘/INDEX.md` 那份 145 KB 手写索引
在卡 F1 的规格里（§1 改写链接 / §3 重算）。脚本算得出它，但**不动盘** —— 见 `PENDING` 表。
"""

from __future__ import annotations

import argparse
import statistics
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

#: 生成物首行（判据 3 的锚点）：改它 = 改判据，别在别处重复这串字面。
GENERATED = "<!-- generated by scripts/gen_doc_index.py; do not edit -->"

#: 只认这五个字段；其余字段（哪怕写了）不进索引 —— 免得索引跟着 frontmatter 一起长胖。
FIELDS = ("title", "mode", "status", "owner", "supersedes")

#: 枚举值（判不出来就按原样打印，不归并、不猜）。
MODES = ("tutorial", "howto", "reference", "explanation")
STATUSES = ("active", "superseded", "draft")

#: 空壳门槛（与旧手写索引同一口径，便于对照）。
SHELL_CHARS = 220

#: 一律不收的目录（判据「不许把索引做成全仓 md 清单」）。
EXCLUDE_PARTS = ("gates/diag", ".wt", ".git")

#: 还没接管的目标 → `--check` 报 SKIP（不冒充通过）。收一条必须写清理由；
#: 接管之后（`--adopt` 跑一次写盘）这条**必须删掉**，否则 `--strict` 会一直红。
PENDING: dict[str, str] = {
    "复盘/INDEX.md": (
        "归 scripts/retro/retro_index.py 全量生成（按 2026-10 底的抽取快照收录，篇数见重算输出 / 主题分区 / 每篇一句话结论）；"
        "本脚本的 render_retro 只会按路径前缀分段，接管会丢掉主题分区与逐篇结论 ⇒ 不接管。"
        "重算：python -X utf8 scripts/retro/retro_extract.py && ... retro_themes/lines/gaps/index"
    ),
}


@dataclass(frozen=True)
class Target:
    """一个索引目标：从哪个目录读、写到哪个文件、按哪种版式渲染。"""

    key: str
    source: str
    output: str
    kind: str  # "docs" | "retro"


TARGETS: tuple[Target, ...] = (
    Target(key="docs", source="docs", output="docs/INDEX.md", kind="docs"),
    Target(key="retro", source="复盘", output="复盘/INDEX.md", kind="retro"),
)


@dataclass(frozen=True)
class Entry:
    """一篇文档在索引里的全部事实（只来自路径、frontmatter 与字符数）。"""

    path: str
    title: str
    mode: str
    status: str
    owner: str
    supersedes: str
    chars: int

    @property
    def labeled(self) -> bool:
        """有文件头 frontmatter ⇒ 已标注；否则一律进「未标注」段。"""
        return bool(self.title or self.mode or self.status or self.owner or self.supersedes)


# --------------------------------------------------------------------- 读


def _read(path: Path) -> str:
    """一律显式 utf-8；坏字节不让整趟崩（坑 19：区域编码会炸在中文路径上）。"""
    return path.read_text(encoding="utf-8", errors="replace")


def parse_frontmatter(text: str) -> dict[str, str]:
    """读文件头 frontmatter（`---` 起、`---` 止的 `key: value` 行）。

    只做最小解析：**不猜**、不展开嵌套、不认多行块。值两侧的引号会去掉，
    这样 `title: "x"` 与 `title: x` 一样看待（两种写法都常见）。
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    fields: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return fields
        key, sep, value = line.partition(":")
        if not sep:
            continue
        name = key.strip().lower()
        if name in FIELDS:
            fields[name] = value.strip().strip("\"'").strip()
    return {}  # 没有闭合的 `---` ⇒ 不算 frontmatter（判据 2：不猜）


def collect(root: Path, target: Target) -> list[Entry]:
    """扫源目录，按路径排序（排序口径固定，输出才可复现）。"""
    base = root / target.source
    if not base.is_dir():
        return []
    entries: list[Entry] = []
    for path in sorted(base.rglob("*.md")):
        rel = path.relative_to(root).as_posix()
        if any(part in rel for part in EXCLUDE_PARTS):
            continue
        if rel == target.output:
            continue  # 别把自己收进自己
        text = _read(path)
        fm = parse_frontmatter(text)
        entries.append(
            Entry(
                path=rel,
                title=fm.get("title", ""),
                mode=fm.get("mode", ""),
                status=fm.get("status", ""),
                owner=fm.get("owner", ""),
                supersedes=fm.get("supersedes", ""),
                chars=len(text),
            )
        )
    return entries


# --------------------------------------------------------------------- 算


def bucket_of(entry: Entry, target: Target) -> str:
    """段 = 路径前缀（`复盘/卡/` 这种）。判据 4 允许的两种信号之一。"""
    rest = entry.path[len(target.source) + 1 :]
    parts = rest.split("/")
    if len(parts) == 1:
        return f"{target.source}/"
    return f"{target.source}/" + "/".join(parts[:-1]) + "/"


def _buckets(entries: list[Entry], target: Target) -> list[tuple[str, list[Entry]]]:
    """按段分组，浅的在前、同深按名字 —— 稳定顺序，输出可复现。"""
    groups: dict[str, list[Entry]] = {}
    for entry in entries:
        groups.setdefault(bucket_of(entry, target), []).append(entry)
    return sorted(groups.items(), key=lambda kv: (kv[0].count("/"), kv[0]))


def _count_by(entries: list[Entry], field: str, values: tuple[str, ...]) -> list[tuple[str, int]]:
    """按枚举值计数；「未标注」= 该字段为空的那批（不猜、不归并）。"""
    rows = [(value, sum(1 for e in entries if getattr(e, field) == value)) for value in values]
    rows.append(("未标注", sum(1 for e in entries if not getattr(e, field))))
    return rows


def _line(entry: Entry) -> str:
    """一篇 = 一行：路径 + title + 其余字段（空的字段不出现）。"""
    if not entry.labeled:
        return f"- `{entry.path}`"
    meta = [f"{name} {getattr(entry, name)}" for name in FIELDS[1:] if getattr(entry, name)]
    tail = f"〔{' · '.join(meta)}〕" if meta else ""
    title = entry.title or "（未写 title）"
    return f"- `{entry.path}` — {title}{tail}"


def _table(head: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return out


def _stats_block(entries: list[Entry], target: Target) -> list[str]:
    if not entries:
        return ["- （没有文件）"]
    chars = [e.chars for e in entries]
    shells = [e for e in entries if e.chars < SHELL_CHARS]
    by_bucket = "、".join(f"`{name}` {len(group)}" for name, group in _buckets(entries, target))
    modes = " / ".join(f"{name} {n}" for name, n in _count_by(entries, "mode", MODES))
    statuses = " / ".join(f"{name} {n}" for name, n in _count_by(entries, "status", STATUSES))
    total = sum(chars)
    return [
        f"- **总篇数**：{len(entries)}",
        f"- **总字数**：{total} 字（约 {total / 10000:.1f} 万字），"
        f"中位 {int(statistics.median(chars))} 字，最长 {max(chars)} 字，最短 {min(chars)} 字",
        f"- **按段**：{by_bucket}",
        f"- **按 mode**：{modes}",
        f"- **按 status**：{statuses}",
        f"- **空壳**（< {SHELL_CHARS} 字）：{len(shells)} 篇",
        "- **口径**：字数是全文字符数（含标点/代码/英文）；「未标注」= 该字段没在 "
        "frontmatter 里出现，如实计数，不猜不补。",
    ]


# --------------------------------------------------------------- 渲染 docs


def render_docs(entries: list[Entry], target: Target) -> str:
    """`docs/INDEX.md`：按 mode 分段 + 未标注段；不摘正文。"""
    counts = _count_by(entries, "mode", MODES)
    out = [
        GENERATED,
        f"# docs 索引（{len(entries)} 篇 · 机器生成）",
        "",
        "> ★ 别手改这份文件：它是 `scripts/gen_doc_index.py` 的产物，`--check` 会把改动咬出来。",
        "> 口径：只读文件头 frontmatter 的 title / mode / status / owner / supersedes；"
        "没有 frontmatter 的文件一律进「未标注」段，如实计数 —— 不猜标题，也不补字段。",
        "> 层次：`AGENTS.md`（薄入口，只做路由）→ 本索引（第二层）→ 具体页；"
        "索引里不内联正文摘录（摘录必然过期）。",
        "",
        "## 计数",
        "",
    ]
    rows = [[name, str(n)] for name, n in counts]
    rows.append(["**合计**", f"**{len(entries)}**"])
    out += _table(["段", "篇数"], rows)
    out += ["", "## 按目录（路径前缀）", ""]
    out += _table(
        ["目录", "篇数", "已标注", "未标注"],
        [
            [f"`{name}`", str(len(group)), str(sum(1 for e in group if e.labeled)),
             str(sum(1 for e in group if not e.labeled))]
            for name, group in _buckets(entries, target)
        ],
    )
    for name, count in counts:
        # 「未标注」那一档 = `mode` 字段为空；其余按枚举值精确匹配（不归并、不猜）。
        group = [e for e in entries if (e.mode == name if name in MODES else not e.mode)]
        out += ["", f"## {name}（{count} 篇）", ""]
        if not group:
            out.append(f"（无：没有 `mode: {name}` 的文件）" if name in MODES
                       else "（无：每一篇都有 frontmatter 的 `mode`）")
        elif name not in MODES:
            out.append("> 这些文件没有文件头 frontmatter。逐篇补 frontmatter 是另一张卡的事 —— "
                       "本卡按「不猜、不补」只列路径；下面按目录分段，免得一大批混成一锅。")
            for bucket, items in _buckets(group, target):
                out += ["", f"**`{bucket}`（{len(items)} 篇）**", ""]
                out += [_line(e) for e in items]
        else:
            out += [_line(e) for e in group]
    out += ["", "## 统计", ""] + _stats_block(entries, target)
    return "\n".join(out) + "\n"


# -------------------------------------------------------------- 渲染 retro


def render_retro(entries: list[Entry], target: Target) -> str:
    """`复盘/INDEX.md`：L0 段表 + 清单 + 统计 + 历史与被推翻（都按机器算）。"""
    superseded = [e for e in entries if e.status == "superseded"]
    referenced = {e.supersedes for e in entries if e.supersedes}
    out = [
        GENERATED,
        f"# 复盘索引（{len(entries)} 篇 · 机器生成）",
        "",
        "> ★ 同 `docs/INDEX.md`：手改会被 `--check` 咬；要改内容就改文件的 frontmatter，再跑脚本。",
        "> 层次：`AGENTS.md`（薄入口）→ 本索引（第二层）→ 原文。本索引**只指路**，"
        "判决一律以原文与 `gates/last.json` 为准，索引不作判据。",
        "",
        "## 0. 怎么用（三层披露）",
        "",
        "1. **L0（§1）**：先看段表（按 frontmatter + 路径前缀），确定你要办的事在哪一堆里。",
        "2. **L1（§2）**：在清单里按卡号 / 门名 / 症状 grep，定位到具体篇。",
        "3. **回原文**：索引不摘正文（摘录必然过期），结论以原文为准。",
        "",
        "## 1. L0 段表（frontmatter + 路径前缀，机器算）",
        "",
    ]
    out += _table(
        ["段", "篇数", "已标注", "未标注"],
        [
            [f"`{name}`", str(len(group)), str(sum(1 for e in group if e.labeled)),
             str(sum(1 for e in group if not e.labeled))]
            for name, group in _buckets(entries, target)
        ],
    )
    out += ["", "## 2. 清单（按段）", ""]
    for index, (name, group) in enumerate(_buckets(entries, target), start=1):
        out += [f"### 2.{index} `{name}`（{len(group)} 篇）", ""]
        out += [_line(e) for e in group]
        out.append("")
    out += ["## 3. 统计（机器算）", ""] + _stats_block(entries, target)
    out += [
        "",
        "## 4. 历史与被推翻（`status: superseded`，机器算）",
        "",
        f"- 标了 `status: superseded` 的：**{len(superseded)} 篇**",
        f"- 被别的篇 `supersedes` 指向的：**{len(referenced)} 篇**",
    ]
    if superseded:
        out.append("")
        out += _table(
            ["文件", "现在以什么为准（`supersedes`）"],
            [
                [f"`{e.path}`", f"`{e.supersedes}`" if e.supersedes else "（没写 `supersedes`）"]
                for e in superseded
            ],
        )
    else:
        out.append("- 名单：（无）")
    out += [
        "",
        "> ★ **判不出来就报 skip，不报 pass**：没有 frontmatter 的文件，脚本无从判断它是否已被"
        "推翻 ⇒ 不进这一节，也**不算**「没有过期文档」。要让它进这一节，只能给文件补 "
        "`status: superseded` + `supersedes:`（那是另一张卡的事）。",
    ]
    return "\n".join(out) + "\n"


RENDER = {"docs": render_docs, "retro": render_retro}


# --------------------------------------------------------------------- 核


def diff_lines(expected: str, actual: str, limit: int = 8) -> list[str]:
    """逐行点名（判据 1）：返回「第 N 行：应为 X，实际 Y」，最多 `limit` 条。"""
    exp = expected.splitlines()
    act = actual.splitlines()
    out: list[str] = []
    for index in range(max(len(exp), len(act))):
        left = exp[index] if index < len(exp) else "（没这一行）"
        right = act[index] if index < len(act) else "（缺这一行）"
        if left != right:
            out.append(f"第 {index + 1} 行：应为 {left!r}，实际 {right!r}")
    return out


def check_target(root: Path, target: Target, adopt: bool, strict: bool) -> tuple[bool, list[str]]:
    """返回（是否会红, 人要看的输出）。"""
    entries = collect(root, target)
    expected = RENDER[target.kind](entries, target)
    out_path = root / target.output
    if not entries:
        return False, [
            f"[SKIP] {target.output}：源目录 `{target.source}/` 不存在或没有 md（判不出来）"
        ]
    if not out_path.exists():
        return True, [f"[FAIL] {target.output}：还没生成 —— 跑 "
                      "`python -X utf8 scripts/gen_doc_index.py`"]
    actual = _read(out_path)
    if not actual.startswith(GENERATED) and target.output in PENDING and not adopt:
        reason = PENDING[target.output]
        line = f"[SKIP] {target.output}：{reason}（判不出来 ⇒ 不冒充通过；接管用 --adopt）"
        return strict, [line]
    if not actual.startswith(GENERATED):
        return True, [f"[FAIL] {target.output}：首行不是 `{GENERATED}` —— "
                      "这份索引不是脚本生成的（或首行被手删了）"]
    if actual == expected:
        return False, [f"[OK  ] {target.output}（{len(entries)} 篇：{_brief(entries)}）"]
    lines = diff_lines(expected, actual)
    head = f"[FAIL] {target.output}：与文件不一致（{len(lines)} 行不同，或行数不同）"
    return True, [head] + [f"       {line}" for line in lines[:8]] + (
        ["       ……（只列前 8 条）"] if len(lines) > 8 else []
    )


def _brief(entries: list[Entry]) -> str:
    parts = [f"{name} {n}" for name, n in _count_by(entries, "mode", MODES)]
    return " / ".join(parts)


def _existing_newline(path: Path) -> str:
    """目标文件现在的行尾（`"\n"` / `"\r\n"` / `"\r"`）；读不到就用 CRLF。

    ★ 只看**第一个行尾**就够：本仓文件是「纯一种行尾」的（混行尾另有一组钉子管），
      这里不做归一 —— 归一属于改内容，不属于写盘。
    ★ 卡 F9（T-AG525）：原来写死 `newline="\n"`，而工作区是 CRLF ⇒ 一重算就整文件
      行尾翻转（405 行全改），与本仓「行尾不许无声归一」的既有钉子同一族问题。
    """
    try:
        raw = path.read_bytes()
    except OSError:
        return "\r\n"
    for i, byte in enumerate(raw):
        if byte == 0x0A:
            return "\r\n" if i and raw[i - 1] == 0x0D else "\n"
        if byte == 0x0D:
            return "\r" if i + 1 < len(raw) and raw[i + 1] != 0x0A else "\r\n"
    return "\r\n"


def write_target(root: Path, target: Target, adopt: bool) -> tuple[bool, list[str]]:
    """写盘。盘上是手写版且没 `--adopt` ⇒ 拒写（不许悄悄覆盖别人的文件）。"""
    entries = collect(root, target)
    if not entries:
        return False, [f"[SKIP] {target.output}：源目录 `{target.source}/` 不存在或没有 md"]
    out_path = root / target.output
    if out_path.exists():
        current = _read(out_path)
        if not current.startswith(GENERATED) and not adopt:
            reason = PENDING.get(target.output, "盘上是手写版")
            return True, [f"[FAIL] {target.output}：{reason} —— 不覆盖（真接管请加 --adopt）"]
    expected = RENDER[target.kind](entries, target)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    newline = _existing_newline(out_path)
    out_path.write_text(expected, encoding="utf-8", newline=newline)
    return False, [f"[write] {target.output}（{len(entries)} 篇：{_brief(entries)}）"]


def print_stats(root: Path) -> None:
    """`--stats`：各段计数（判据 4 要的「数字由机器算」，不必先写盘）。"""
    for target in TARGETS:
        entries = collect(root, target)
        modes = " / ".join(f"{name} {n}" for name, n in _count_by(entries, "mode", MODES))
        statuses = " / ".join(f"{name} {n}" for name, n in _count_by(entries, "status", STATUSES))
        print(f"[stats] {target.output} ← {target.source}/**：{len(entries)} 篇")
        print(f"        mode：{modes}")
        print(f"        status：{statuses}")
        for name, group in _buckets(entries, target):
            labeled = sum(1 for e in group if e.labeled)
            print(f"        段 {name}：{len(group)} 篇（已标注 {labeled}）")


# --------------------------------------------------------------------- 入口


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="由文件头 frontmatter 生成文档索引")
    parser.add_argument("--root", type=Path, default=ROOT, help="仓库根（测试用，默认本仓）")
    parser.add_argument("--check", action="store_true", help="只核对，不写盘")
    parser.add_argument("--stats", action="store_true", help="只打印各段计数")
    parser.add_argument("--target", choices=[*(t.key for t in TARGETS), "all"], default="all")
    parser.add_argument(
        "--adopt",
        nargs="*",
        default=None,
        metavar="输出路径",
        help="接管盘上手写版（如 --adopt 复盘/INDEX.md）；只写 --adopt 不带值时接管 PENDING 全部",
    )
    parser.add_argument("--strict", action="store_true", help="把 SKIP 也当红（自证用）")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    wanted = [t for t in TARGETS if args.target in ("all", t.key)]
    # None = 没给这个参数；[] = 给了但没跟路径 ⇒ 接管 PENDING 里全部。
    adopted = set(PENDING) if args.adopt == [] else set(args.adopt or [])

    if args.stats:
        print_stats(root)
        return 0

    failed = False
    for target in wanted:
        adopt = target.output in adopted
        if args.check:
            red, lines = check_target(root, target, adopt, args.strict)
        else:
            red, lines = write_target(root, target, adopt)
        failed = failed or red
        for line in lines:
            print(line)
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
